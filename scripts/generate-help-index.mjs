// Builds content/help/index.generated.ts (the headings for "On this page" and
// the plain-text search sections of every guide article) and
// content/help/bodies.generated.ts (one static import per article), so the
// guide never reads MDX files at runtime or imports a path built from a URL.
// `--check` fails when either file is stale (CI and the frontend build).
import ts from "typescript";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const defaultContentRoot = path.join(root, "content", "help");
export const indexFileName = "index.generated.ts";
export const bodiesFileName = "bodies.generated.ts";

// The same pure helpers the app uses (lib/help/text.ts), compiled on the fly
// so headings and anchors can never drift from what the pages render.
async function loadTextHelpers() {
  const helperSource = readFileSync(path.join(root, "lib", "help", "text.ts"), "utf8");
  const compiled = ts.transpileModule(helperSource, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
  return import(`data:text/javascript;base64,${Buffer.from(compiled).toString("base64")}`);
}

function mdxSlugs(contentRoot, directory = contentRoot) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) return mdxSlugs(contentRoot, full);
    return entry.name.endsWith(".mdx") ? [path.relative(contentRoot, full).split(path.sep).join("/").replace(/\.mdx$/, "")] : [];
  });
}

const header = (what) => [
  "// Generated by scripts/generate-help-index.mjs from content/help/**/*.mdx.",
  `// Do not edit by hand: run \`npm run help:index\` after ${what}.`,
].join("\n");

/** The generated index module: headings and search sections per article. */
export async function buildHelpIndexSource(contentRoot = defaultContentRoot) {
  const { extractHeadings, extractSearchSections } = await loadTextHelpers();
  const index = {};
  for (const slug of mdxSlugs(contentRoot).sort()) {
    const source = readFileSync(path.join(contentRoot, `${slug}.mdx`), "utf8");
    index[slug] = { headings: extractHeadings(source), sections: extractSearchSections(source) };
  }
  return [
    header("changing an article"),
    'import type { HelpHeading, HelpSearchSection } from "@/lib/help/text";',
    "",
    "export type HelpIndexEntry = { headings: readonly HelpHeading[]; sections: readonly HelpSearchSection[] };",
    "",
    `export const helpIndex: Readonly<Record<string, HelpIndexEntry>> = ${JSON.stringify(index, null, 2)};`,
    "",
  ].join("\n");
}

/** Static loaders for every article body, so bundlers see each MDX file. */
export function buildHelpBodiesSource(contentRoot = defaultContentRoot) {
  const loaders = mdxSlugs(contentRoot).sort().map((slug) => `  ${JSON.stringify(slug)}: () => import(${JSON.stringify(`./${slug}.mdx`)}),`);
  return [
    header("adding or removing an article"),
    'import type { MDXContent } from "mdx/types";',
    "",
    "export const helpArticleBodies: Readonly<Record<string, () => Promise<{ default: MDXContent }>>> = {",
    ...loaders,
    "};",
    "",
  ].join("\n");
}

function readCommitted(file) {
  try {
    return readFileSync(file, "utf8").replace(/\r\n/g, "\n");
  } catch {
    return ""; // missing counts as stale
  }
}

/** Whether both committed files match the articles (line endings ignored). */
export async function helpIndexIsCurrent(contentRoot = defaultContentRoot) {
  return readCommitted(path.join(contentRoot, indexFileName)) === await buildHelpIndexSource(contentRoot)
    && readCommitted(path.join(contentRoot, bodiesFileName)) === buildHelpBodiesSource(contentRoot);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.includes("--check")) {
    if (!(await helpIndexIsCurrent())) {
      console.error("content/help/*.generated.ts is stale. Run npm run help:index.");
      process.exit(1);
    }
    console.log("Guide index verified.");
  } else {
    writeFileSync(path.join(defaultContentRoot, indexFileName), await buildHelpIndexSource());
    writeFileSync(path.join(defaultContentRoot, bodiesFileName), buildHelpBodiesSource());
    console.log("Guide index written.");
  }
}
